package cloud.golem.types;

import java.util.Objects;

/**
 * Represents an index into the operation log (oplog).
 *
 * <p>The oplog is Golem's durability mechanism that records all operations
 * performed by a worker. The oplog index identifies a specific point in
 * the operation history.
 */
public final class OplogIndex {

    private final long value;

    public OplogIndex(long value) {
        this.value = value;
    }

    public long getValue() {
        return value;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (o == null || getClass() != o.getClass()) return false;
        OplogIndex that = (OplogIndex) o;
        return value == that.value;
    }

    @Override
    public int hashCode() {
        return Objects.hash(value);
    }

    @Override
    public String toString() {
        return "OplogIndex{" + value + "}";
    }
}
